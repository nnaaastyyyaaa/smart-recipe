def _parse_catalog() -> dict[str, list[tuple[str, str]]]:
    catalog: dict[str, list[tuple[str, str]]] = {}
    for category, raw in _RAW_CATALOG.items():
        products: list[tuple[str, str]] = []
        for chunk in raw.replace("\n", ";").split(";"):
            chunk = chunk.strip()
            if not chunk:
                continue
            name, _, tags = chunk.partition("|")
            products.append((name.strip(), tags.strip()))
        catalog[category] = products
    return catalog


# Категорія -> список (назва продукту, теги порушень)
CATALOG = _parse_catalog()


def _product_restrictions() -> list[tuple[str, str]]:
    pairs: set[tuple[str, str]] = set()
    for products in CATALOG.values():
        for name, tags in products:
            for tag in tags:
                for restriction in TAG_TO_RESTRICTIONS[tag]:
                    pairs.add((name, restriction))
    return sorted(pairs)


